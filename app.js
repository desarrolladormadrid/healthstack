let currentLang = localStorage.getItem('lang') || 'es';
let settings = JSON.parse(localStorage.getItem('healthSettings') || '{}');

function t(key) {
    return (translations[currentLang] && translations[currentLang][key]) || translations.es[key] || key;
}

function detectLanguage() {
    const saved = localStorage.getItem('lang');
    if (saved) return saved;
    const lang = navigator.language || navigator.userLanguage || 'es';
    const prefix = lang.split('-')[0].toLowerCase();
    if (['en', 'hi', 'zh', 'ru'].includes(prefix)) return prefix;
    return 'es';
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;
    updateAllTexts();
    document.getElementById('currentLang').textContent = lang.toUpperCase();
    document.querySelectorAll('.lang-option').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    document.getElementById('langDropdown').classList.remove('show');
}

function updateAllTexts() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = t(key);
        if (text) el.textContent = text;
    });
    updateGreeting();
    renderWeeklyChart();
}

function updateGreeting() {
    const hour = new Date().getHours();
    const name = settings.userName || '';
    let greeting;
    if (hour < 12) greeting = t('greetingMorning');
    else if (hour < 18) greeting = t('greetingAfternoon');
    else greeting = t('greetingEvening');
    document.getElementById('greeting').textContent = name ? `${greeting}, ${name}` : greeting;

    const date = new Date();
    const options = { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' };
    document.getElementById('dateText').textContent = date.toLocaleDateString(
        currentLang === 'es' ? 'es-ES' : currentLang === 'hi' ? 'hi-IN' : currentLang === 'zh' ? 'zh-CN' : currentLang === 'ru' ? 'ru-RU' : 'en-GB',
        options
    );
}

function renderWeeklyChart() {
    const canvas = document.getElementById('weeklyChart');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    const rect = canvas.parentElement.getBoundingClientRect();
    canvas.width = rect.width * 2;
    canvas.height = rect.height * 2;
    ctx.scale(2, 2);
    const w = rect.width;
    const h = rect.height;

    ctx.clearRect(0, 0, w, h);

    const days = [t('mon'), t('tue'), t('wed'), t('thu'), t('fri'), t('sat'), t('sun')];
    const data = [65, 80, 45, 90, 70, 55, 85];
    const barWidth = (w - 60) / 7;
    const maxBarH = h - 40;

    days.forEach((day, i) => {
        const x = 30 + i * barWidth;
        const barH = (data[i] / 100) * maxBarH;
        const y = h - 25 - barH;

        const grad = ctx.createLinearGradient(x, y, x, h - 25);
        grad.addColorStop(0, 'rgba(56, 189, 248, 0.8)');
        grad.addColorStop(1, 'rgba(56, 189, 248, 0.2)');
        ctx.fillStyle = grad;

        const radius = 4;
        ctx.beginPath();
        ctx.moveTo(x + radius, y);
        ctx.lineTo(x + barWidth - 10 - radius, y);
        ctx.quadraticCurveTo(x + barWidth - 10, y, x + barWidth - 10, y + radius);
        ctx.lineTo(x + barWidth - 10, h - 25);
        ctx.lineTo(x, h - 25);
        ctx.lineTo(x, y + radius);
        ctx.quadraticCurveTo(x, y, x + radius, y);
        ctx.fill();

        ctx.fillStyle = '#64748b';
        ctx.font = '10px Inter';
        ctx.textAlign = 'center';
        ctx.fillText(day, x + (barWidth - 10) / 2, h - 8);
    });
}

function initNavigation() {
    const tabs = ['dashboard', 'activitySection', 'nutritionSection', 'recordsSection', 'settingsSection'];
    document.querySelectorAll('.nav-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const tab = btn.dataset.tab;
            tabs.forEach(t => {
                const el = document.getElementById(t);
                if (el) el.style.display = 'none';
            });
            const target = document.getElementById(tab);
            if (target) {
                target.style.display = '';
                target.classList.add('active');
                if (tab === 'dashboard') target.classList.add('animate-in');
            }
            document.querySelectorAll('.nav-btn').forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
        });
    });
}

function initLangSelector() {
    const btn = document.getElementById('langBtn');
    const dropdown = document.getElementById('langDropdown');
    btn.addEventListener('click', (e) => {
        e.stopPropagation();
        dropdown.classList.toggle('show');
    });
    document.addEventListener('click', () => dropdown.classList.remove('show'));
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') dropdown.classList.remove('show');
    });
    document.querySelectorAll('.lang-option').forEach(opt => {
        opt.addEventListener('click', () => setLanguage(opt.dataset.lang));
    });
}

function loadSettings() {
    const defaults = { userName: '', userAge: '', userWeight: '72', userHeight: '175', stepsGoal: '10000', waterGoal: '2.5', caloriesGoal: '2000' };
    settings = { ...defaults, ...settings };
    document.getElementById('userName').value = settings.userName;
    document.getElementById('userAge').value = settings.userAge;
    document.getElementById('userWeight').value = settings.userWeight;
    document.getElementById('userHeight').value = settings.userHeight;
    document.getElementById('stepsGoal').value = settings.stepsGoal;
    document.getElementById('waterGoal').value = settings.waterGoal;
    document.getElementById('caloriesGoal').value = settings.caloriesGoal;
}

function saveSettings() {
    settings = {
        userName: document.getElementById('userName').value,
        userAge: document.getElementById('userAge').value,
        userWeight: document.getElementById('userWeight').value,
        userHeight: document.getElementById('userHeight').value,
        stepsGoal: document.getElementById('stepsGoal').value,
        waterGoal: document.getElementById('waterGoal').value,
        caloriesGoal: document.getElementById('caloriesGoal').value,
    };
    localStorage.setItem('healthSettings', JSON.stringify(settings));
    updateGreeting();
    showToast(t('saved'));
}

function showToast(msg) {
    let toast = document.querySelector('.toast');
    if (!toast) {
        toast = document.createElement('div');
        toast.className = 'toast';
        document.body.appendChild(toast);
    }
    toast.textContent = msg;
    toast.classList.add('show');
    setTimeout(() => toast.classList.remove('show'), 2000);
}

function animateMetrics() {
    const cards = document.querySelectorAll('.metric-card');
    cards.forEach((card, i) => {
        card.style.opacity = '0';
        card.style.transform = 'translateY(20px)';
        setTimeout(() => {
            card.style.transition = 'all 0.4s ease';
            card.style.opacity = '1';
            card.style.transform = 'translateY(0)';
        }, i * 80);
    });
}

function updateHealthScore() {
    const steps = parseInt(document.getElementById('stepsValue').textContent.replace(/,/g, ''));
    const stepsGoal = parseInt(settings.stepsGoal) || 10000;
    const stepsScore = Math.min(30, (steps / stepsGoal) * 30);
    const sleepScore = 25;
    const waterScore = 20;
    const activityScore = 15;
    const score = Math.round(stepsScore + sleepScore + waterScore + activityScore);
    document.getElementById('healthScore').textContent = score;

    const circle = document.querySelector('.score-circle');
    if (circle) {
        const circumference = 327;
        const offset = circumference - (score / 100) * circumference;
        circle.style.strokeDashoffset = offset;
    }
}

function initMetricTaps() {
    document.querySelectorAll('.metric-card').forEach(card => {
        card.addEventListener('click', () => {
            const metric = card.dataset.metric;
            const value = card.querySelector('.metric-value');
            if (metric === 'water') {
                const current = parseFloat(value.textContent);
                value.textContent = (current + 0.2).toFixed(1) + 'L';
                showToast(`+0.2L ${t('water')}`);
            } else if (metric === 'steps') {
                const current = parseInt(value.textContent.replace(/,/g, ''));
                value.textContent = (current + 200).toLocaleString();
                showToast('+200 ' + t('steps'));
            } else if (metric === 'calories') {
                const current = parseInt(value.textContent.replace(/,/g, ''));
                value.textContent = (current + 50).toLocaleString();
                showToast('+50 kcal');
            }
            updateHealthScore();
        });
    });
}

function init() {
    currentLang = detectLanguage();
    document.documentElement.lang = currentLang;
    setLanguage(currentLang);
    loadSettings();
    initNavigation();
    initLangSelector();
    initMetricTaps();
    animateMetrics();
    updateHealthScore();

    document.getElementById('saveSettings').addEventListener('click', saveSettings);

    setTimeout(renderWeeklyChart, 100);
    window.addEventListener('resize', renderWeeklyChart);
}

document.addEventListener('DOMContentLoaded', init);
